"""Setting 3 — independently assembled realistic streams from Wikidata statement histories.

Phase A (needs the bridge worker's `fetch` op; public CC0 data):
  1. a SPARQL query selects humans with >=3 employer (P108) statements of which >=1 has an
     end date and >=1 statement of any tracked property has deprecated rank;
  2. for each selected entity (and the organisations that appear as employers) the revision
     list is fetched, up to 40 revisions are sampled across its history, and each sampled
     revision's JSON is fetched.
Phase B (free): consecutive sampled revisions are diffed on tracked properties; every
  change becomes an observation with belief time = revision day index:
    claim added              -> assert (valid cue 'since' when P580 start qualifier present)
    claim removed            -> retract of that observation
    rank -> deprecated       -> retract of that observation (the community withdrew it)
    value changed in place   -> assert of the new value with a 'correction' cue of the old
                                observation when the old is removed in the same revision
  Sources: a reference with P248 'stated in' pointing to an authority/registry item ->
  trusted (origin = that item); a reference URL -> standard (origin = domain); no
  reference -> low (origin = 'wd_unreferenced'). Conflict labels and reliabilities are
  hidden from systems: only the class/origin declaration is visible, as in Settings 1-2.
  Queries are generated by the shared event-driven/grid templates; gold by the oracle.
Usage:
  python scripts/build_setting3.py select            -> writes bridge/requests/s3_select.json
  python scripts/build_setting3.py plan              -> reads response, writes revision-list requests
  python scripts/build_setting3.py revisions         -> reads lists, samples, writes content requests
  python scripts/build_setting3.py build OUTDIR      -> diffs, writes streams + gold
"""
import collections, datetime as dt, json, os, random, re, sys, urllib.parse
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BR = os.path.join(ROOT, "bridge")
TRACK = {"P108": "employer", "P551": "residence", "P39": "position", "P27": "citizenship", "P569": "birth_date", "P159": "hq_city", "P169": "ceo"}
ATTRS = {
    "employer":    {"type": "entity", "cardinality": "multi",  "changeable": False, "error_allowed": True, "competing_values": False},
    "residence":   {"type": "entity", "cardinality": "multi",  "changeable": True,  "error_allowed": True},
    "position":    {"type": "entity", "cardinality": "single", "changeable": True,  "error_allowed": True},
    "citizenship": {"type": "entity", "cardinality": "multi",  "changeable": False, "error_allowed": True, "competing_values": False},
    "birth_date":  {"type": "date",   "cardinality": "single", "changeable": False, "error_allowed": True},
    "hq_city":     {"type": "entity", "cardinality": "single", "changeable": True,  "error_allowed": True},
    "ceo":         {"type": "entity", "cardinality": "single", "changeable": True,  "error_allowed": True},
    "work_city":   {"type": "entity", "cardinality": "multi",  "changeable": True,  "error_allowed": False, "derived": True},
    "ceo_city":    {"type": "entity", "cardinality": "single", "changeable": True,  "error_allowed": False, "derived": True},
}
RULES = [
    {"id": "r_work", "kind": "defeasible", "head": ["work_city", "?e", "?c"], "body": [["employer", "?e", "?x"], ["hq_city", "?x", "?c"]]},
    {"id": "r_ceo_city", "kind": "defeasible", "head": ["ceo_city", "?o", "?c"], "body": [["ceo", "?o", "?p"], ["work_city", "?p", "?c"]]},
]
SPARQL = """
SELECT DISTINCT ?p WHERE {
  ?p wdt:P31 wd:Q5 .
  ?p p:P108 ?s1 . ?s1 pq:P582 ?end .
  { SELECT ?p (COUNT(?s) AS ?n) WHERE { ?p p:P108 ?s } GROUP BY ?p HAVING (?n >= 3) }
  ?p ?prop ?st . ?st wikibase:rank wikibase:DeprecatedRank .
  FILTER(?prop IN (p:P108, p:P551, p:P39, p:P27, p:P569))
} LIMIT 60
"""
AUTHORITY_HINTS = ("library", "registry", "register", "census", "official", "gazette", "companies house", "sec ", "parliament", "government", "database", "catalogue", "catalog", "archive", "viaf", "isni", "orcid")


def _req(name, urls):
    os.makedirs(os.path.join(BR, "requests"), exist_ok=True)
    json.dump({"op": "fetch", "urls": urls}, open(os.path.join(BR, "requests", name + ".json"), "w"))
    print(f"wrote bridge/requests/{name}.json with {len(urls)} urls")


def _resp(name):
    p = os.path.join(BR, "responses", name + ".json")
    return json.load(open(p)) if os.path.exists(p) else None


def _file(entry):
    return os.path.join(ROOT, entry["file"]) if entry and "file" in entry else None


def select():
    url = "https://query.wikidata.org/sparql?format=json&query=" + urllib.parse.quote(SPARQL)
    _req("s3_select", [url])


def plan():
    r = _resp("s3_select")
    entry = next(iter(r.values()))
    data = json.load(open(_file(entry)))
    qids = [b["p"]["value"].rsplit("/", 1)[1] for b in data["results"]["bindings"]]
    random.Random(0).shuffle(qids)
    qids = qids[:40]
    json.dump(qids, open(os.path.join(BR, "s3_qids.json"), "w"))
    urls = [f"https://www.wikidata.org/w/api.php?action=query&prop=revisions&titles={q}&rvlimit=500&rvprop=ids|timestamp&format=json&rvdir=newer" for q in qids]
    _req("s3_revlists", urls)


def revisions(per_entity=40):
    r = _resp("s3_revlists")
    sample = {}
    for url, entry in r.items():
        f = _file(entry)
        if not f:
            continue
        d = json.load(open(f))
        page = next(iter(d["query"]["pages"].values()))
        revs = page.get("revisions", [])
        q = page["title"]
        if len(revs) > per_entity:
            idx = sorted(set(int(i * (len(revs) - 1) / (per_entity - 1)) for i in range(per_entity)))
            revs = [revs[i] for i in idx]
        sample[q] = [(rv["revid"], rv["timestamp"]) for rv in revs]
    json.dump(sample, open(os.path.join(BR, "s3_revsample.json"), "w"))
    urls = [f"https://www.wikidata.org/w/api.php?action=query&prop=revisions&revids={rid}&rvprop=content|timestamp|ids&rvslots=main&format=json"
            for q, rs in sample.items() for rid, _ in rs]
    _req("s3_revcontent", urls)


def _claims(entity_json, pid):
    out = {}
    claims = entity_json.get("claims", {})
    if not isinstance(claims, dict):          # early revisions serialise an empty claim set as []
        claims = {}
    for c in claims.get(pid, []):
        snak = c.get("mainsnak", {})
        dv = snak.get("datavalue", {}).get("value")
        if dv is None:
            continue
        if isinstance(dv, dict) and "id" in dv:
            v = dv["id"]
        elif isinstance(dv, dict) and "time" in dv:
            v = dv["time"][1:11]
            prec = dv.get("precision", 11)           # 9 = year, 10 = month, 11 = day
            v = v[:4] if prec <= 9 else (v[:7] if prec == 10 else v)
        else:
            v = str(dv)
        quals = c.get("qualifiers", {})
        start = quals.get("P580", [{}])[0].get("datavalue", {}).get("value", {}).get("time") if "P580" in quals else None
        refs = c.get("references", [])
        if start:                                   # year/month precision -> first day of the period
            start = start[1:11].replace("-00-00", "-01-01").replace("-00", "-01")
        out[c["id"]] = {"value": v, "rank": c.get("rank"), "start": start,
                        "ref": _source_of(refs)}
    return out


def _source_of(refs):
    for ref in refs:
        sn = ref.get("snaks", {})
        if "P248" in sn:
            item = sn["P248"][0].get("datavalue", {}).get("value", {}).get("id")
            return ("stated_in", item)
        if "P854" in sn:
            url = sn["P854"][0].get("datavalue", {}).get("value", "")
            dom = urllib.parse.urlparse(url).netloc.lower().replace("www.", "")
            return ("url", dom)
    return ("none", "wd_unreferenced")


PERSON_ATTRS = ("employer", "residence", "position", "citizenship", "birth_date")
ORG_ATTRS = ("hq_city", "ceo")


def _load_revisions(resp_name):
    """{entity: [(timestamp, entity_json), ...]} from a revision-content response file."""
    r = _resp(resp_name) or {}
    by_entity = collections.defaultdict(list)
    for url, entry in r.items():
        f = _file(entry)
        if not f or not os.path.exists(f):
            continue
        d = json.load(open(f))
        page = next(iter(d["query"]["pages"].values()))
        rv = page["revisions"][0]
        content = rv["slots"]["main"].get("*") or rv["slots"]["main"].get("content")
        try:
            ej = json.loads(content)
        except Exception:
            continue
        by_entity[page["title"]].append((rv["timestamp"], ej))
    for q in by_entity:
        by_entity[q].sort(key=lambda x: x[0])
    return by_entity


def _events(q, revs, attrs):
    """Diff consecutive revisions of entity q on the given attributes. Returns a list of events
    with absolute timestamps: {"ts", "kind": assert|retract, "attr", "value", "start", "source",
    "cls", "op_of": <event index>, "target": <event index>}."""
    ev = []
    live = {}                       # claim id -> event index of its current assertion
    prev = {pid: {} for pid in TRACK}
    for ts, ej in revs:
        for pid, attr in TRACK.items():
            if attr not in attrs:
                continue
            cur = _claims(ej, pid)
            for cid, c in cur.items():
                kind, origin = c["ref"]
                cls = "low" if kind == "none" else ("standard" if kind == "url" else ("trusted" if any(h in origin.lower() for h in AUTHORITY_HINTS) else "standard"))
                skey = re.sub(r"[^a-z0-9_]", "_", f"{kind}_{origin}".lower())[:40]
                if cid not in prev[pid]:
                    if c["rank"] == "deprecated":
                        continue
                    ev.append({"ts": ts, "kind": "assert", "entity": q, "attr": attr, "value": c["value"], "start": c["start"], "source": skey, "cls": cls})
                    live[cid] = len(ev) - 1
                else:
                    p = prev[pid][cid]
                    if p["rank"] != "deprecated" and c["rank"] == "deprecated" and cid in live:
                        ev.append({"ts": ts, "kind": "retract", "target": live.pop(cid)})
                    elif p["value"] != c["value"] and cid in live:
                        ev.append({"ts": ts, "kind": "assert", "entity": q, "attr": attr, "value": c["value"], "start": c["start"], "source": skey, "cls": cls, "op_of": live[cid]})
                        live[cid] = len(ev) - 1
            for cid in set(prev[pid]) - set(cur):
                if cid in live:
                    ev.append({"ts": ts, "kind": "retract", "target": live.pop(cid)})
            prev[pid] = cur
    return ev


def _day(ts, t0):
    return max(1, (dt.datetime.fromisoformat(ts.replace("Z", "+00:00")) - t0).days + 1)


def build(outdir, label_lookup=None):
    from revise_stream.model import stream_from_dict
    from revise_stream.gold import all_gold
    from revise_stream import oracle_v1
    from revise_stream.generator import Gen, GenConfig, select_queries, write_stream
    persons = _load_revisions("s3_revcontent")
    orgs = _load_revisions("s3_org_revcontent")
    org_events = {q: _events(q, revs, ORG_ATTRS) for q, revs in orgs.items()}
    os.makedirs(outdir, exist_ok=True)
    stats = []
    for q, revs in persons.items():
        t0 = dt.datetime.fromisoformat(revs[0][0].replace("Z", "+00:00"))
        events = _events(q, revs, PERSON_ATTRS)
        # merge the histories of the organisations this person is reported to have worked for
        employers = sorted({e["value"] for e in events if e["kind"] == "assert" and e["attr"] == "employer"})
        groups = [events] + [org_events[o] for o in employers if o in org_events]
        merged = []
        for gi, g in enumerate(groups):
            for ei, e in enumerate(g):
                merged.append((e["ts"], gi, ei, e))
        merged.sort(key=lambda x: (x[0], x[1], x[2]))
        # day 1 = the earliest date in the stream: the first revision, or the earliest stated
        # start qualifier (P580) if it lies before it, so that 'since' cues before the first
        # revision keep their order (valid time may precede belief time)
        starts = []
        for _, _, _, e in merged:
            if e.get("start"):
                try:
                    starts.append(dt.datetime.fromisoformat(e["start"][:10]).replace(tzinfo=dt.timezone.utc))
                except Exception:
                    pass
        if starts and min(starts) < t0:
            t0 = min(starts)
        idmap = {}
        obs, sources, entities = [], {}, {q}
        for ts, gi, ei, e in merged:
            if e["kind"] == "retract":
                if (gi, e["target"]) not in idmap:
                    continue
                obs.append({"id": f"o{len(obs) + 1}", "t": _day(ts, t0), "source": "wd_editors", "kind": "retract", "target": idmap[(gi, e["target"])]})
                sources.setdefault("wd_editors", {"class": "standard", "origin": "wd_editors"})
                continue
            o = {"id": f"o{len(obs) + 1}", "t": _day(ts, t0), "source": e["source"], "kind": "assert", "entity": e["entity"], "attr": e["attr"], "value": e["value"]}
            sources.setdefault(e["source"], {"class": e["cls"], "origin": e["source"]})
            if e.get("start"):
                try:
                    sd = (dt.datetime.fromisoformat(e["start"][:10]).replace(tzinfo=dt.timezone.utc) - t0).days + 1
                    if 1 <= sd <= o["t"]:
                        o["valid"] = {"cue": "since", "t": sd}
                except Exception:
                    pass
            if "op_of" in e and (gi, e["op_of"]) in idmap:
                o["op_cue"], o["op_of"] = "correction", idmap[(gi, e["op_of"])]
            idmap[(gi, ei)] = o["id"]
            obs.append(o)
            entities.add(e["entity"])
            if ATTRS[e["attr"]]["type"] == "entity":
                entities.add(e["value"])
        if len(obs) < 8:
            continue
        # cap per-key assertions at 7 (keep earliest 7) for enumeration bounds; drop dangling references
        cnt = collections.Counter()
        kept, kept_ids = [], set()
        for o in obs:
            if o["kind"] == "assert":
                cnt[(o["entity"], o["attr"])] += 1
                if cnt[(o["entity"], o["attr"])] > 7:
                    continue
                if "op_of" in o and o["op_of"] not in kept_ids:
                    o.pop("op_of"); o.pop("op_cue")
            elif o["target"] not in kept_ids:
                continue
            kept.append(o); kept_ids.add(o["id"])
        d = {"stream_id": f"s3_{q}", "meta": {"source": "wikidata revision history", "entity": q, "n_revisions": len(revs), "base_date": t0.date().isoformat(),
                                              "organisations": [o for o in employers if o in org_events]},
             "domain": {"entities": sorted(entities), "attributes": ATTRS, "rules": RULES}, "sources": sources,
             "observations": kept, "queries": []}
        s = stream_from_dict(d)
        g = Gen(GenConfig(seed=0)); g.obs = kept; g.entities = sorted(entities)
        qs = g.make_queries_generic(s)
        d["queries"] = qs
        s = stream_from_dict(d)
        gold = all_gold(s, oracle_v1.interpretations)
        keep = set(select_queries(s, gold, 44, random.Random(0), quota=(0.35, 0.25, 0.40)))
        d["queries"] = [x for x in qs if x["id"] in keep]
        gold = {k: v for k, v in gold.items() if k in keep}
        write_stream(os.path.join(outdir, f"{d['stream_id']}.json"), d, {"world": [], "truth": {}, "poison": []}, gold)
        n_down = sum(1 for x in d["queries"] if gold[x["id"]]["warranted"] and s.attributes[x.get("attr")].derived) if hasattr(s, "attributes") else None
        stats.append({"entity": q, "n_obs": len(kept), "n_q": len(d["queries"]), "warranted": sum(1 for v in gold.values() if v["warranted"]),
                      "n_orgs": len(d["meta"]["organisations"])})
    json.dump(stats, open(os.path.join(outdir, "_stats.json"), "w"), indent=1)
    print(f"built {len(stats)} streams; mean obs={sum(x['n_obs'] for x in stats)/max(1,len(stats)):.1f} mean warranted={sum(x['warranted'] for x in stats)/max(1,len(stats)):.2f} mean orgs={sum(x['n_orgs'] for x in stats)/max(1,len(stats)):.1f}")


if __name__ == "__main__":
    cmd = sys.argv[1]
    {"select": select, "plan": plan, "revisions": revisions}.get(cmd, lambda: build(sys.argv[2]))()
